"""Объект badge: темная плашка-подпись с цветной точкой."""
from ..core import obj, P
from .. import mat


@obj("badge", "Темная плашка-подпись с цветной точкой, для названий и коротких пояснений",
     ["label"], (220, 48),
     params={"label": P("str", "", anim=True, desc="короткий текст плашки, лучше до 16 символов, длинный сильно уменьшается")},
     anchors={"bottom": (0, 24), "top": (0, -24)})
def draw(c, p, t):
    """Нарисовать плашку с текстом label."""
    col = mat.tc(p["theme"])
    mat.shadow(c, (0, 0, 220, 48), 9, 6, 8, 110)
    mat.plate(c, (0, 0, 220, 48), "", 22, col)
    mat.led(c, (18, 24), 4, col, True)
    c.fit_text((126, 24), p["label"][:28], 22, (240, 244, 250, 255), 172)
