"""Объект room: комната офиса в разрезе (окно, лампа, дверь, табличка)."""
import math
from ..core import obj, P
from .. import mat


def _mx(a, b, k):
    """Смешать цвета a и b на долю k."""
    return tuple(int(a[i] + (b[i] - a[i]) * k) for i in range(3))


@obj("room", "Комната офиса в разрезе: стена, пол, окно, лампа и дверь; внутри ставят оборудование",
     ["container", "building"], (260, 300),
     params={
         "lights": P("num", 0.0, 0, 1, anim=True, desc="свет в комнате: лампа и окно, 0 темно, 1 ярко"),
         "door": P("choice", "closed", choices=["closed", "open"], anim=True, desc="дверь закрыта или открыта"),
         "label": P("str", "", anim=True, desc="табличка над дверью, до 10 символов"),
     },
     anchors={"door": (95, 80), "floor": (0, 135), "top": (0, -150)})
def draw(c, p, t):
    """Нарисовать комнату; lights задает свет, door состояние двери."""
    col = mat.tc(p["theme"])
    L = p["lights"]
    warm = (255, 205, 120)
    mat.shadow(c, (0, 0, 260, 300), 10, 10, 14, 150)
    mat.grad_rrect(c, (0, 0, 260, 300), 10, [(0, _mx((44, 50, 64), (70, 62, 60), L * 0.5)), (1, (24, 28, 36))])
    if L > 0.02:
        c.glow((160, 28, 240, 98), lambda s: s.rrect((160, 28, 240, 98), 4, fill=warm + (200,)), rad=26, gain=L, sharp=False)
    c.rrect((0, 262, 260, 300), 10, fill=(16, 19, 26, 255))
    c.line([(4, 262), (256, 262)], (110, 120, 140, 160), 1.5)
    mat.grad_rrect(c, (160, 28, 240, 98), 4, [(0, _mx((22, 30, 52), warm, L)), (1, _mx((14, 18, 30), (210, 150, 80), L))])
    c.line([(200, 28), (200, 98)], (14, 17, 24, 255), 3)
    c.line([(160, 63), (240, 63)], (14, 17, 24, 255), 3)
    c.rrect((160, 28, 240, 98), 4, outline=(150, 158, 172, 220), w=2)
    c.line([(95, 0), (95, 22)], (120, 128, 142, 255), 2)
    if L > 0.02:
        c.glow((82, 22, 108, 34), lambda s: s.rrect((82, 22, 108, 34), 6, fill=warm + (255,)), rad=16, gain=L)
    c.poly([(80, 34), (110, 34), (104, 22), (86, 22)], _mx((60, 66, 80), warm, L) + (255,))
    if p["door"] == "closed":
        mat.grad_rrect(c, (186, 150, 244, 262), 4, [(0, (74, 82, 96)), (1, (46, 52, 64))])
        c.circle((197, 208), 3, fill=(215, 220, 230, 255))
    else:
        c.rrect((186, 150, 244, 262), 4, fill=(8, 10, 14, 255))
        c.poly([(186, 150), (208, 158), (208, 254), (186, 262)], (62, 68, 82, 255))
    c.rrect((186, 150, 244, 262), 4, outline=(150, 158, 172, 220), w=2)
    if p["label"]:
        mat.plate(c, (178, 120, 252, 144), p["label"][:10], 13, col)
    c.rrect((0, 0, 260, 300), 10, outline=(150, 158, 172, 210), w=2)
